'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),{JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const first=html.indexOf('const DEFAULT_CATS = [');
const defaultsEnd=html.indexOf('const DEFAULT_ACCOUNT_TREE',first);
const managerStart=html.indexOf('function getCats(){',defaultsEnd);
const managerEnd=html.indexOf('const DEFAULT_ACCOUNT_CODES =',managerStart);
assert(first>0&&defaultsEnd>first&&managerStart>defaultsEnd&&managerEnd>managerStart);
const dom=new JSDOM('<!doctype html><html lang="ar"><body><div id="pctRows"></div><p id="pctSum"></p><button id="addCatBtn"></button><button id="savePctsBtn"></button><button id="resetPctsBtn"></button></body></html>',
  {url:'https://ratib.test',runScripts:'outside-only'});
const w=dom.window,d=w.document;
const storeData={},writes=[];
w.store={get:(k,dflt)=>Object.prototype.hasOwnProperty.call(storeData,k)?storeData[k]:dflt,
 set:(k,v)=>{storeData[k]=v;writes.push(k)}};
w.PALETTE=['#3b82f6','#10b981'];w.showToast=()=>{};
let notices=[],nextPrompt='';
w.alert=message=>notices.push(message);
w.confirm=()=>true;
w.prompt=()=>nextPrompt||'بند جديد';
w.eval(html.slice(first,defaultsEnd)+html.slice(managerStart,managerEnd)+
  '\nwindow.budgetTest={getCats,init:()=>{draftCats=getCats(true).map(c=>({...c}));renderCategoryRows()},draft:()=>draftCats};');
const api=w.budgetTest;
assert.equal(api.getCats().length,10,'All default categories survive first run');
assert(api.getCats().find(c=>c.id==='general'),'General fallback is always available');
api.init();
assert.equal(d.querySelectorAll('.ratib-budget-manage-item').length,10);
const general=[...d.querySelectorAll('.ratib-budget-manage-item')].find(n=>n.querySelector('.ratib-budget-name').value==='عام');
assert(general.querySelector('.ratib-budget-delete').disabled,'General remains an editable but required voucher fallback');
const originalName=general.querySelector('.ratib-budget-name');
originalName.value='عمومي';originalName.dispatchEvent(new w.Event('input'));
const type=general.querySelector('.ratib-budget-type');
type.value='text';type.dispatchEvent(new w.Event('change'));
assert(general.querySelector('.ratib-budget-percent').hidden,'Text categories have no configured percentages');
assert(d.getElementById('pctSum').textContent.includes('نصية: 1'));
d.getElementById('savePctsBtn').click();
assert(notices.some(x=>x.includes('100%')),'Relative allocations must total 100 before saving');
assert.equal(writes.length,0,'Invalid relative percentage total must not persist');
type.value='percent';type.dispatchEvent(new w.Event('change'));
const pct=general.querySelector('.ratib-budget-value');
pct.value='5';pct.dispatchEvent(new w.Event('input'));
d.getElementById('savePctsBtn').click();
assert.equal(writes.length,1);
assert.equal(api.getCats().find(c=>c.id==='general').name,'عمومي','Renamed category persists without changing its stable ID');
nextPrompt='بند اختبار نصي';
d.getElementById('addCatBtn').click();
const newRow=[...d.querySelectorAll('.ratib-budget-manage-item')].find(n=>n.querySelector('.ratib-budget-name').value===nextPrompt);
assert(newRow,'New category created');
assert.equal(newRow.querySelector('.ratib-budget-type').value,'text','New category defaults to label-only');
newRow.querySelector('.ratib-budget-delete').click();
assert(api.draft().find(c=>c.name===nextPrompt).archived,'Deletion archives instead of erasing ID');
assert(d.querySelector('.ratib-budget-archived'),'Archive is visible for restoration');
d.getElementById('savePctsBtn').click();
assert(!api.getCats().some(c=>c.name===nextPrompt),'Archived item disappears from new dropdowns');
assert(api.getCats(true).some(c=>c.name===nextPrompt),'Historical metadata remains retrievable');
const archived=api.getCats(true).find(c=>c.name===nextPrompt);
assert.equal(archived.type,'text');
const historicalTransaction={distribution:{[archived.id]:{amount:150}},currency:'YER'};
assert(historicalTransaction.distribution[api.getCats(true).find(c=>c.id===archived.id).id].amount===150,'Old transaction reference remains stable');
assert(writes.every(x=>x==='cats'),'Manager never mutates accounting records');
const archiveItem=[...d.querySelectorAll('.ratib-budget-archived-item')].find(x=>x.textContent.includes(nextPrompt));
archiveItem.querySelector('button').click();
d.getElementById('savePctsBtn').click();
assert(api.getCats().some(c=>c.id===archived.id),'Archived category can be restored');
assert(!html.includes('MAX_BUDGET_CATS'),'Category count stays unlimited');
assert(html.includes('const reportingCats=[...cats,...getCats(true).filter(c=>c.archived)]'),'Budget reports retain archived categories');
w.close();
console.log('PASS Ratib 3.6.164: editable category names/types/colors, percentages, text-only labels and reversible archive');
