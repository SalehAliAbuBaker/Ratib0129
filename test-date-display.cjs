const fs=require('fs'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const dom=new JSDOM('<body><form><div id="a"><input type="date" value="2026-10-28" aria-label="التاريخ"></div><div id="b"></div></form><div id="reportAccountOpsPanel">سند 2026-10-28</div></body>',{runScripts:'outside-only',pretendToBeVisual:true,url:'https://ratib.test'});
const w=dom.window;w.RatibAndroid={};
w.eval(fs.readFileSync('ratib-date-display.js','utf8'));
const wait=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 await wait(65);
 const input=w.document.querySelector('#a input'),button=w.document.querySelector('.ratib-native-date-button');
 assert.ok(button,'reuses single voucher date field, with overlay button');
 assert.equal(input.type,'date');
 assert.equal(input.value,'2026-10-28','retains canonical ISO date');
 assert.ok(/\d+ .+\dهـ$/.test(button.querySelector('span').textContent),'Hijri appears first with هـ joined to the year');
 assert.equal(button.querySelector('small').textContent,'2026-10-28','compact corresponding Gregorian date');
 assert.equal(w.document.querySelectorAll('#a input').length,1,'no extra date inputs in voucher');
 assert.ok(w.document.querySelector('#reportAccountOpsPanel .ratib-hijri-text'),'decorates account statement text');
 assert.equal(w.document.querySelector('#reportAccountOpsPanel .ratib-hijri-text small').textContent,'2026-10-28');
 input.value='2027-01-02';
 assert.equal(button.querySelector('small').textContent,'2027-01-02','synchronizes programmatic updates');
 w.document.querySelector('#b').append(input);
 await wait(75);
 assert.equal(input.parentElement.className,'ratib-native-date-wrap','reconnects moved original input');
 assert.equal(w.document.querySelectorAll('.ratib-native-date-wrap').length,1,'no duplicate wrappers');
 button.click();
 assert.equal(w.document.querySelector('#ratib-hijri-dialog').hidden,false,'opens actual Hijri picker');
 assert.ok(w.document.querySelectorAll('#rhDays button').length>=29,'offers Hijri days');
 const other=w.document.querySelector('#rhOther');
 other.checked=false;other.dispatchEvent(new w.Event('change'));
 assert.equal(button.querySelector('small'),null,'can hide the corresponding date');
 other.checked=true;other.dispatchEvent(new w.Event('change'));
 const main=w.document.querySelector('#rhMain');
 main.value='g';main.dispatchEvent(new w.Event('change'));
 assert.equal(button.querySelector('span').textContent,'2027-01-02','Gregorian-first user choice');
 assert.ok(button.querySelector('small').textContent.includes('هـ'),'Hijri becomes the small corresponding date');
 main.value='h';main.dispatchEvent(new w.Event('change'));
 assert.equal(button.querySelector('small').textContent,'2027-01-02');
 assert.equal(w.document.querySelector('#rhEngine'),null,'No calendar-method selector survives');
 assert.equal(w.document.querySelector('#rhLocal'),null,'No local month offsets survive');
 assert.equal(w.RatibHijriFirst.calendar,'umalqura','Only Umm al-Qura is supported');
 const greg=w.document.querySelector('#rhGregorianDate');
 assert(greg&&greg.type==='date','Gregorian date replaces the method selector');
 assert.equal(input.value,'2027-01-02','changing display preferences never alters saved ledger date');
 assert(!w.document.querySelector('#ratib-hijri-dialog').textContent.includes('الهجري الحسابي'));
 assert(!w.document.querySelector('#ratib-hijri-dialog').textContent.includes('اليمني المحلي'));
 const different=[...w.document.querySelectorAll('#rhDays button')].find(x=>x.getAttribute('aria-pressed')==='false');
 assert.ok(different,'another day selectable');
 const previous=input.value;different.click();
 assert.notEqual(input.value,previous,'picking Hijri day updates same underlying ISO field');
 assert.equal(w.document.querySelector('#ratib-hijri-dialog').hidden,true,'picker closes after selection');
 input.value='';
 assert.equal(button.querySelector('span').textContent,'اختر التاريخ');
 w.document.querySelector('form').reset();await wait(60);
 assert.equal(input.value,'2026-10-28','form reset preserves original value');
 assert.equal(button.querySelector('small').textContent,'2026-10-28','form reset refreshes Hijri interface');
 console.log('PASS Hijri-first date: single original ISO input, Umm al-Qura, compact counterpart, statement, picker, preferences, Umm al-Qura only, Gregorian picker, move, reset');
 
})().catch(e=>{console.error(e);process.exitCode=1});