'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),{JSDOM}=require('jsdom');
const sidebar=fs.readFileSync('ratib-sidebar-3.6.124.js','utf8');
const css=fs.readFileSync('ratib-theme.css','utf8');
const nav=fs.readFileSync('ratib-navigation-v3.css','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const markup='<html lang="ar"><head><meta name="theme-color" content="#0d5b45"></head><body><button id="sidebarMenuBtn"></button><button id="backToMenuBtn"><span>رجوع</span></button><aside id="appSidebar"><div class="sidebar-nav"></div><div class="sidebar-footer"></div></aside><section id="pageSettings"></section></body></html>';
function create(stored){
 const dom=new JSDOM(markup,{url:'https://ratib.test/',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window;w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};
 if(stored!==undefined)w.localStorage.setItem('ratib.ui.palette.v1',stored);
 w.eval(sidebar);w.dispatchEvent(new w.Event('load'));return dom;
}
let dom=create(),w=dom.window,d=w.document;
assert.equal(w.RatibPalette.get(),'green','official green remains the default');
assert.equal(d.documentElement.dataset.ratibPalette,'green');
assert.equal(d.querySelector('meta[name="theme-color"]').content,'#0d5b45');
const card=d.getElementById('ratibPaletteSettingsCard');
assert(card,'palette choices are available in official Settings');
assert.equal(card.querySelectorAll('input[name="ratibPalette"]').length,4);
assert(card.querySelector('input[value="green"]').checked);
assert(d.getElementById('appSidebar').textContent.includes('ألوان واجهة راتب'));
w.localStorage.setItem('ratib.accounting.data','unchanged');
const gold=card.querySelector('input[value="gold"]');gold.checked=true;gold.dispatchEvent(new w.Event('change',{bubbles:true}));
assert.equal(w.RatibPalette.get(),'gold');assert.equal(w.localStorage.getItem('ratib.ui.palette.v1'),'gold');
assert.equal(w.localStorage.getItem('ratib.accounting.data'),'unchanged');
assert.equal(d.querySelector('meta[name="theme-color"]').content,'#8a6323');
assert(!card.querySelector('input[value="green"]').checked);
assert.equal(w.RatibPalette.set('blue'),true);assert(card.querySelector('input[value="blue"]').checked);
assert.equal(w.localStorage.getItem('ratib.ui.palette.v1'),'blue');
assert.equal(w.RatibPalette.set('emerald'),true);assert(card.querySelector('input[value="emerald"]').checked);assert.equal(w.localStorage.getItem('ratib.ui.palette.v1'),'emerald');assert.equal(d.querySelector('meta[name="theme-color"]').content,'#047857');
assert.equal(w.RatibPalette.set('unsafe'),false);
dom.window.close();
dom=create('emerald');assert.equal(dom.window.RatibPalette.get(),'emerald','saved emerald choice is restored');dom.window.close();
dom=create('blue');assert.equal(dom.window.RatibPalette.get(),'blue','saved choice is restored');dom.window.close();
dom=create('invalid');assert.equal(dom.window.RatibPalette.get(),'green','invalid choice defaults to green');dom.window.close();
assert(css.includes(':root[data-ratib-palette="gold"]')&&css.includes(':root[data-ratib-palette="blue"]')&&css.includes(':root[data-ratib-palette="emerald"]'));
assert(css.includes('@media print')&&css.includes('[data-theme="dark"]'));
assert(!nav.includes('background:#0d5b45!important'),'navigation accent follows active theme');
assert(sw.includes('v227-official-whatsapp-support-3.6.113'),'updated palette resources are cached for offline operation');
console.log('PASS official green default; gold/blue instant change, preference storage, invalid guard, accounting preservation, offline cache');
