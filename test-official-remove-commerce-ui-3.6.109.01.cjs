'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),{JSDOM}=require('jsdom');
const read=x=>fs.readFileSync(x,'utf8');
const html=read('index.html'),fav=read('ratib-favorites-v3.js'),home=read('ratib-trial-home-sidebar-3.6.143.js'),sidebar=read('ratib-sidebar-3.6.124.js'),sw=read('sw.js'),pkg=require('./package.json');
const release='3.6.109.01';
assert.equal(pkg.version,release);
assert(html.includes('const RATIB_RELEASE={"version":"'+release+'","build":"p10901"'));
assert(sw.includes('const APP_RELEASE={"version":"'+release+'","build":"p10901"'));
assert(sw.includes("v219-official-simple-home-"+release));
assert(html.includes('الإصدار '+release) && !html.includes('الإصدار '+release+' (تجريبية)'));
const dom=new JSDOM(html,{url:'https://salehaliabubaker.github.io/Ratib0129/',runScripts:'outside-only'});
const d=dom.window.document,homeNode=d.getElementById('dashboardHomeContent');
assert(homeNode);
const tiles=[...homeNode.querySelectorAll('.main-menu-grid > button.main-menu-btn')];
assert.deepEqual(tiles.map(x=>x.textContent.trim()),['إضافة','سجل العمليات','التقارير','الحسابات']);
assert.equal(homeNode.querySelectorAll('.ratib-commerce-shortcuts,.ratib-commerce-shortcut').length,0);
assert(!homeNode.textContent.includes('المخزون')&&!homeNode.textContent.includes('الوارد')&&!homeNode.textContent.includes('الصادر'));
assert.equal(d.querySelectorAll('#pageCommerce').length,1,'retired legacy content mount remains for historic data only');
assert.equal(d.getElementById('ratibCommerceDefaults').hidden,true,'commerce account defaults cannot appear under regular settings');
assert(d.querySelector('[data-ledger-voucher-type="commerce"]'),'older commercial transactions must remain filterable');
assert(d.querySelector('[data-ledger-voucher-type="commerce"]').closest('label').textContent.includes('سابقة'));
assert(!fav.includes('const commerceFavorites='),'retired commerce feature must not be available to add to favorites');
assert(fav.includes("!id.startsWith('commerce:')"),'old commerce favorites must be removed from shown favorites');
assert(!fav.includes('<option>المخزون</option>'));
assert(!fav.includes('<option>الوارد</option>'));
assert(!fav.includes('<option>الصادر</option>'));
assert(home.includes("if (!carousel || carousel.dataset.ratibPolished === '1') return;"),'dashboard must still initialize when shortcuts are gone');
assert(!home.includes('if (!carousel || !commerce'));
assert(html.includes("if(saved.view.tab==='pageCommerce')return;"),'old commerce view must not auto-reopen');
assert(sidebar.includes('(?:\\.\\d+)?'),'sidebar version must recognize four-part official releases');
assert(html.includes("const CLOUD_FOLDER_NAME = 'Ratib Backups'"),'official cloud folder remains unchanged');
assert(html.includes("const CLOUD_FILE_PREFIX = 'ratib-cloud-'"),'official backup filename prefix remains unchanged');
assert(html.includes("const CLOUD_CFG_KEY = 'cloud_backup_cfg'"),'existing cloud storage key must remain unchanged');
assert(html.includes("store.get('commerce_v1',null)"),'historic commerce data must remain readable for accounting statements');
for(const [name,source] of [['favorites',fav],['dashboard',home],['sw',sw]])assert.doesNotThrow(()=>new Function(source),name+' must parse');
dom.window.close();
console.log('PASS official 3.6.109.01: simplified main UI, retired favorites, historic voucher retention and official backup continuity');
