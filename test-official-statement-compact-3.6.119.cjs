'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const css=fs.readFileSync('ratib-statement-compact-3.6.119.css','utf8');
const src=fs.readFileSync('ratib-statement-compact-3.6.119.js','utf8');
const pkg=require('./package.json');
assert.equal(pkg.version,'3.6.120');
assert(html.includes('const RATIB_RELEASE={"version":"3.6.120","build":"p12000"'));
assert(sw.includes('const APP_RELEASE={"version":"3.6.120","build":"p12000"'));
assert(sw.includes('v235-official-statement-totals-3.6.120'));
assert(sw.includes('"./ratib-statement-compact-3.6.119.css"')&&sw.includes('"./ratib-statement-compact-3.6.119.js"'));
assert(html.includes('ratib-statement-compact-3.6.119.css?v=3.6.120')&&html.includes('ratib-statement-compact-3.6.119.js?v=3.6.120'));
assert(css.includes('grid-column:1 / span 7!important')&&css.includes('grid-column:8 / -1!important'));
assert(css.includes('grid-row:2!important'));
assert(!src.includes('localStorage')&&!src.includes('store.set('),'Layout does not change account data or marks');
(async()=>{
 const dom=new JSDOM('<!doctype html><html><body><div id="pageAccountOperations"><div id="ratibAccountMovementSearchBar"><label class="ratib-movement-search-label" for="ratibAccountMovementSearchInput">البحث في حركات الحساب</label><input id="ratibAccountMovementSearchInput" type="search"></div><div id="accountOperationsStandalonePanel"><div class="account-currency-track"><div class="account-statement-row" data-tx-id="x"></div></div></div></div></body></html>',{url:'https://example.org/',runScripts:'outside-only'});
 const w=dom.window,document=w.document;
 const search=document.getElementById('ratibAccountMovementSearchBar'),panel=document.getElementById('accountOperationsStandalonePanel'),input=document.getElementById('ratibAccountMovementSearchInput');
 input.value='بيان محاسبي';
 let fired=0;input.addEventListener('input',()=>fired++);
 w.eval(src);
 document.dispatchEvent(new w.Event('DOMContentLoaded'));
 await new Promise(resolve=>setTimeout(resolve,0));
 assert.equal(panel.firstElementChild,search,'search relocated ahead of cards');
 assert.equal(input.placeholder,'البحث في حركات الحساب');
 assert.equal(search.querySelector('.ratib-movement-search-label'),null,'redundant label removed');
 const markbar=document.createElement('div');markbar.className='ratib-statement-markbar';panel.prepend(markbar);
 await new Promise(resolve=>setTimeout(resolve,0));
 assert.equal(markbar.nextElementSibling,search,'search located immediately after marks');
 panel.innerHTML='<div class="account-currency-track"></div>';
 await new Promise(resolve=>setTimeout(resolve,0));
 assert.equal(panel.firstElementChild,search,'search preserved after render');
 assert.equal(input.value,'بيان محاسبي','typed query preserved');
 input.dispatchEvent(new w.Event('input',{bubbles:true}));
 assert.equal(fired,1,'search input listener preserved');
 w.close();
 console.log('PASS official 3.6.119: compact statement, search placement, preserved filters and marks');
})().catch(e=>{console.error(e);process.exitCode=1;});
