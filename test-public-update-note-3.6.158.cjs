/* Trial 3.6.159: same one-line update notice for pending updates and a freshly loaded release. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),{JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8').replace(/\r\n/g,'\n'),worker=fs.readFileSync('sw.js','utf8').replace(/\r\n/g,'\n');
const fixed='إزالة شاشة اختيار السند المكررة نهائيًا';
const line=worker.split('\n').find(x=>x.startsWith('const APP_RELEASE='));
assert(line,'Worker release manifest must exist');
const manifest=JSON.parse(line.slice('const APP_RELEASE='.length).replace(/;$/,''));
const trial=html.match(/const RATIB_RELEASE=\{"version":"([^"]+)"/)?.[1];
assert(trial,'Current trial version must exist in app');
assert.equal(manifest.version,trial,'Worker and page must share one release version');
assert.match(trial,/^3\.6\.\d+\.\d{2}$/,'Trial version must use current four-part numbering');
assert(manifest.changes.length>=3,'Manifest must describe the release');
assert(Array.isArray(manifest.highlights)&&manifest.highlights.length>0&&manifest.highlights.every(x=>typeof x==='string'&&x.trim()),'Current release must include valid headlines');
assert(worker.includes(trial),'Offline cache must include the actual release');
assert(html.includes('RATIB_RELEASE={"version":"'+trial+'"'));
assert(!html.includes('ratib-commerce-3.6.131.js'),'Retired commerce script must not load');
const at=html.indexOf("const RATIB_PUBLIC_UPDATE_NOTE=");
const until=html.indexOf('function showTransientAppNotice(',at);
assert(at>0&&until>at);
const dom=new JSDOM('<!doctype html><html><body><div id="appUpdateDetails" class="hidden"></div></body></html>',{url:'https://ratibtrial.pages.dev/',runScripts:'outside-only'});
const w=dom.window;
w.eval(html.slice(at,until)+';window.showAppReleaseDetailsTest=showAppReleaseDetails;');
const box=w.document.getElementById('appUpdateDetails');
w.showAppReleaseDetailsTest({version:trial,changes:['تفصيل أول','تفصيل ثان','تفصيل ثالث']});
assert.equal(box.textContent,fixed,'Only the public summary is visible');
assert.equal(box.querySelectorAll('li,ul').length,0,'No detailed bullet points');
assert(!box.classList.contains('hidden'));
w.showAppReleaseDetailsTest(null);
assert(box.classList.contains('hidden'),'An unrelated status notice hides release details');
w.showAppReleaseDetailsTest({version:trial,changes:[fixed]});
assert.equal(box.textContent,fixed);
dom.window.close();
console.log('PASS '+trial+': short public update note, worker backward compatibility, no detailed list');
