'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('ratib-statement-footer-opening-3.6.157.css','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const pkg=require('./package.json');
assert.equal(pkg.version,'3.6.180');
assert(html.includes('ratib-statement-footer-opening-3.6.157.css?v=3.6.180'));
assert(sw.includes('"./ratib-statement-footer-opening-3.6.157.css"'));
assert(css.includes('grid-template-columns:minmax(0,1fr)!important'));
assert(css.includes('#openingHeader #openingDateLabel'));
assert(css.includes('.ratib-native-date-button'));
assert(css.includes('@media screen')&&!css.includes('@media print'));
const start=html.indexOf('const RATIB_STATEMENT_NOTICE_DEFAULT='),end=html.indexOf('function preparePrintStatementTemplate(',start);
assert(start>0&&end>start,'Helpers must precede rendering');
const memory=new Map(),localStorage={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)};
const context={localStorage,tafqitAccountCurrency:(n,c)=>'تفقيط '+n+' '+c,console};
vm.createContext(context);
vm.runInContext(html.slice(start,end),context);
assert.match(vm.runInContext("ratibStatementClosingText(1500,'YER')",context),/لكم.*تفقيط 1500 YER/);
assert.match(vm.runInContext("ratibStatementClosingText(-250,'SAR')",context),/عليكم.*تفقيط 250 SAR/);
assert.doesNotMatch(vm.runInContext("ratibStatementClosingText(0,'USD')",context),/عليكم|لكم/);
assert.match(vm.runInContext('ratibStatementNoticeText()',context),/14 يومًا/);
vm.runInContext("ratibSaveStatementNoticeSettings({show:true,text:'نص خاص'})",context);
assert.equal(vm.runInContext('ratibStatementNoticeText()',context),'نص خاص');
vm.runInContext("ratibSaveStatementNoticeSettings({show:false,text:'نص مخفي'})",context);
assert.equal(vm.runInContext('ratibStatementNoticeText()',context),'');
assert(html.includes('id="ratibStatementNoticeInput"')&&html.includes('id="ratibStatementNoticeEnabled"'));
assert(html.includes('id="ratibStatementNoticeReset"'));
assert(html.includes('const footerHeight=')&&html.includes('const footerWordsLines=')&&html.includes('const footerNoticeLines='));
assert(html.includes('ratibStatementClosingText(closingBal,currency)'));
assert(html.includes('ratibStatementClosingText(data.closing,data.currency)'));
const dom=new JSDOM(html),d=dom.window.document;
assert(d.getElementById('printStatementContainer')?.querySelector('#psStatementNotice'));
assert(d.getElementById('ratibPageNav')?.querySelector('#backToMenuBtn'));
dom.window.close();
console.log('PASS 3.6.170: signed balance, editable notice, canvas output and opening date width');
