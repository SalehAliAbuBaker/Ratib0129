'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('index.html','utf8');
const start=html.indexOf('function ratibStatementInclusiveTotals(data)');
const end=html.indexOf('\n}',start)+2;
assert(start>=0&&end>start,'inclusive statement calculation must exist');
const context={roundAccountingAmount:value=>Math.round((value+Number.EPSILON)*100)/100};
vm.createContext(context);vm.runInContext(html.slice(start,end),context);
const sum=data=>context.ratibStatementInclusiveTotals(data);
let t=sum({opening:-10300,totalDebit:170900,totalCredit:181200});
assert.equal(t.debit,181200);assert.equal(t.credit,181200);assert.equal(-10300+181200-170900,0);
t=sum({opening:35600,totalDebit:119000,totalCredit:86600});
assert.equal(t.debit,119000);assert.equal(t.credit,122200);
t=sum({opening:0,totalDebit:250,totalCredit:30});
assert.equal(t.debit,250);assert.equal(t.credit,30);
for(const snippet of ['const inclusive=ratibStatementInclusiveTotals(data)','const printTotals=ratibStatementInclusiveTotals','const totals=ratibStatementInclusiveTotals(data)','ratibStatementInclusiveTotals(data).credit.toLocaleString()'])assert(html.includes(snippet),snippet);
