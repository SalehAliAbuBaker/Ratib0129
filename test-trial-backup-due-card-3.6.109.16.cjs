'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),{JSDOM}=require('jsdom');
const script=fs.readFileSync('ratib-backup-due-card.js','utf8');
const html=fs.readFileSync('index.html','utf8'),sw=fs.readFileSync('sw.js','utf8');
const currentRelease=require('./package.json').version;
assert(html.includes('ratib-backup-due-card.js?v='+currentRelease));
assert(html.includes('ratib-backup-due-card.css?v='+currentRelease));
assert(sw.includes('"./ratib-backup-due-card.js"')&&sw.includes('"./ratib-backup-due-card.css"'));
assert(html.includes('window.RatibBackupDueCard?.check?.()'));
assert(!html.includes('const ok = await runCloudBackup(false);'),'No background Cloud upload without user choice');
assert(html.includes('async function writeAutoBackup()')&&html.includes('return true;'),'Manual local backup reports real outcome');
async function test(){
 const dom=new JSDOM('<!doctype html><html lang="ar"><body></body></html>',{url:'https://ratibtrial.pages.dev/',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window,d=w.document,values={auto_backup_enabled:true,auto_backup_last_time:new Date(Date.now()-4*3600000).toISOString()};
 let cloud=true,cloudCalls=0,localCalls=0;
 w.store={get:(k,def=null)=>Object.hasOwn(values,k)?values[k]:def,set:(k,v)=>{values[k]=v;}};
 w.cloudBackupDue=()=>cloud;
 w.writeAutoBackup=async()=>{localCalls++;values.auto_backup_last_time=new Date().toISOString();return true;};
 w.runCloudBackup=async(interactive,destination)=>{assert.equal(interactive,true);assert.equal(destination,'trial');cloudCalls++;cloud=false;return true;};
 w.flushStorage=async()=>{};
 w.showToast=()=>{};
 w.eval(script);
 const api=w.RatibBackupDueCard;
 api.check();
 const card=d.getElementById('ratibBackupDueCard');
 assert(card&&!card.hidden,'Card appears when both backups due');
 assert(d.getElementById('ratibBackupDueMessage').textContent.includes('السحابي والمحلي'));
 assert.equal(cloudCalls,0,'Passive checks never upload');
 assert.equal(localCalls,0,'Passive checks never write a manual backup');
 d.getElementById('ratibBackupDueLater').click();
 assert(card.hidden,'Postponement hides reminder');
 assert(values.ratib_backup_reminder_postpone_until_v1>Date.now());
 api.check();assert(card.hidden,'Do not show while postponed');
 values.ratib_backup_reminder_postpone_until_v1=0;api.check();
 assert(!card.hidden,'Reminder returns once postpone expires');
 d.getElementById('ratibBackupDueSave').click();
 for(let i=0;i<8;i++)await new Promise(resolve=>setImmediate(resolve));
 assert.equal(cloudCalls,1);assert.equal(localCalls,1);
 assert(card.hidden,'Card closes after both confirmed');
 values.auto_backup_last_time=new Date(Date.now()-4*3600000).toISOString();
 api.check();assert(!card.hidden,'Local-only due still prompts');
 assert(d.getElementById('ratibBackupDueMessage').textContent.includes('المحلية'));
 dom.window.close();
 console.log('PASS trial backup due: cloud/local combination, 1h defer, explicit save, no background upload, success confirmation');
}
test().catch(e=>{console.error(e);process.exitCode=1;});
