'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=x=>fs.readFileSync(require('node:path').join(__dirname,x),'utf8');
const html=read('index.html');
const sw=read('sw.js');
const nav=read('ratib-navigation-v3.js');
const trial=html.match(/const RATIB_RELEASE=\{"version":"([^"]+)"/)?.[1];
const worker=sw.match(/const APP_RELEASE=\{"version":"([^"]+)"/)?.[1];
assert.equal(trial,'3.6.149','Deployed trial release must remain 3.6.149');
assert.equal(worker,trial,'App shell and worker must share one release');
assert(!nav.includes("const VERSION='3.6.123'"),'Legacy navigation script must not hardcode 3.6.123');
assert(!nav.includes('RATIB_RELEASE.version=VERSION'),'Navigation must not mutate the release manifest');
assert(!nav.includes('version116'),'Legacy version locking flag must be removed');
assert(nav.includes('function hasChanges()')&&nav.includes('hookToast()'),'Keep unsaved changes warning and toast hook');
assert(html.includes('ratib-navigation-v3.js?v='+trial),'Navigation must be cache-busted with active release');
assert(sw.includes('v167-remove-stale-123-badge-3.6.149'),'Worker must refresh cached navigation resources');
new Function(nav);
console.log('PASS trial 3.6.149: navigation no longer overwrites release badge with 3.6.123');
