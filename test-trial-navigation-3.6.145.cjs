'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = name => fs.readFileSync(path.join(__dirname,name),'utf8');
const html = read('index.html'), ui = read('ratib-commerce-3.6.131.js');
const css = read('ratib-commerce-3.6.131.css');
const sidebar = read('ratib-sidebar-3.6.124.js'), worker = read('sw.js'), pkg = require('./package.json');
const currentVersion=html.match(/const RATIB_RELEASE=\{"version":"(\d+\.\d+\.\d+)"/)?.[1];
assert(currentVersion,'Trial HTML must declare a version');
assert(html.includes('الإصدار '+currentVersion+' (تجريبية)'));
assert(worker.includes('"version":"'+currentVersion+'"'));
assert(worker.includes('-'+currentVersion+"'"),'Offline cache must be stamped with the active release');
assert.equal(pkg.version,currentVersion);
assert.match(html,/ratib-commerce-3\.6\.131\.js\?v=3\.6\.\d+/);
assert.match(html,/ratib-sidebar-3\.6\.124\.js\?v=3\.6\.\d+/);
assert.match(ui,/data-rc-toggle-new/);
assert.match(ui,/data-rc-direct-type/);
assert.match(ui,/types=\{in:\['أمر توريد','توريد مخزني','فاتورة مشتريات'\],out:\['أمر صرف','صرف مخزني','فاتورة مبيعات'\]\}/);
assert(!ui.includes('id="rc-doctype"'), 'No standalone document type selector allowed');
assert.match(css,/\.rc-new-menu\[hidden\]/);
assert.match(sidebar,/window\.RatibSettingsOpen=openSetting/);
assert.match(sidebar,/focusSetting\(key,true\)/);
assert.match(sidebar,/const main=getCard\(key\)/);
assert.match(html,/if \(!\(window\.google && google\.accounts && google\.accounts\.oauth2\)\)/);
assert.match(html,/if \(interactive\) throw new Error\('اكتمل تجهيز تسجيل الدخول إلى Google/);
assert.match(html,/window\.RatibSettingsOpen\('backupsettings'\)/);
assert(!html.includes('license://' ) && !html.includes('intent://'),'No forced app link during Google sign-in');
console.log('PASS 3.6.146: trial release, document menu, settings route, Google auth gesture, cache consistency');
