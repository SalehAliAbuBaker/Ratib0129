'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8').replace(/\r\n/g,'\n');
const start=html.indexOf('function ratibRestorePrintScreen(){');
const end=html.indexOf('function outputBudgetReport(',start);
assert(start>0&&end>start,'print recovery functions must be in the core app');
const snippet=html.slice(start,end);
assert(snippet.includes('window.addEventListener(\'pageshow\',onPageShow)'));
assert(snippet.includes("document.addEventListener('visibilitychange',onVisibility)"));
assert(html.includes('function navigateToTab(target, pushToHistory = true) {\n  // Never leave a stale printing-'));
assert(html.includes('function goBackInApp(){\n  ratibRestorePrintScreen();'));
assert(html.includes('function handleRatibPopState(){\n  ratibRestorePrintScreen();'));
const dom=new JSDOM('<!doctype html><html lang="ar"><head></head><body><div id="pageCommerce"></div><div id="pageDashboard"></div></body></html>',{
 url:'https://ratibtrial.pages.dev/',runScripts:'outside-only',pretendToBeVisual:true
});
const w=dom.window,d=w.document;
let printCalls=0,savedDelay=null,hidden=false;
Object.defineProperty(d,'hidden',{configurable:true,get:()=>hidden});
w.RatibPrintLogo={syncPrint:()=>{}};
w.ratibPaperLandscape=()=>false;
w.showToast=()=>{};
w.print=()=>{printCalls++;};
const originalSetTimeout=w.setTimeout.bind(w);
w.setTimeout=(fn,delay)=>{savedDelay=delay;return originalSetTimeout(fn,delay);};
w.eval(snippet);
assert.equal(w.printRatibDocument('printing-voucher'),true);
assert.equal(printCalls,1);
assert(d.body.classList.contains('printing-voucher'));
assert(savedDelay<=8000,'fallback must not block returning to app for a minute');
hidden=true;d.dispatchEvent(new w.Event('visibilitychange'));
hidden=false;d.dispatchEvent(new w.Event('visibilitychange'));
assert(!d.body.classList.contains('printing-voucher'),'return from native print UI restores app');
assert.equal(w.__ratibPrintCleanup,null);
assert.equal(w.printRatibDocument('printing-budget'),true);
assert(d.body.classList.contains('printing-budget'));
w.dispatchEvent(new w.Event('afterprint'));
assert(!d.body.classList.contains('printing-budget'),'standard afterprint still works');
assert.equal(w.printRatibDocument('printing-statement'),true);
w.dispatchEvent(new w.Event('pageshow'));
assert(!d.body.classList.contains('printing-statement'),'Android PWA resume recovers screen');
assert.equal(w.printRatibDocument('printing-commerce'),true);
w.ratibRestorePrintScreen();
assert(!d.body.classList.contains('printing-commerce'),'back/navigation can always cancel stale print');
d.body.classList.add('printing-statement','trial-printing','account-print-mode');
w.ratibRestorePrintScreen();
assert([...d.body.classList].every(x=>!x.startsWith('printing-')&&x!=='trial-printing'&&x!=='account-print-mode'));
w.print=()=>{throw Error('unsupported WebView');};
assert.equal(w.printRatibDocument('printing-voucher'),false);
assert(!d.body.classList.contains('printing-voucher'),'print exception must restore screen');
dom.window.close();
console.log('PASS trial 3.6.108.07: print cleanup on Android resume/afterprint/back/failure');
