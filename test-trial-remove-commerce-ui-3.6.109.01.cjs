'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),{JSDOM}=require('jsdom');
const read=x=>fs.readFileSync(x,'utf8');
const html=read('index.html'),fav=read('ratib-favorites-v3.js'),home=read('ratib-trial-home-sidebar-3.6.143.js'),sidebar=read('ratib-sidebar-3.6.124.js'),sw=read('sw.js'),pkg=require('./package.json');
const release=pkg.version;
assert.equal(pkg.version,release);
assert(html.includes('const RATIB_RELEASE={"version":"'+release+'"'));
assert(sw.includes('const APP_RELEASE={"version":"'+release+'"'));
assert(sw.includes('-'+release+"';"),'cache follows current version');
assert(html.includes('الإصدار '+release+' (تجريبية)'),'trial label must remain visibly trial');
const dom=new JSDOM(html,{url:'https://ratibtrial.pages.dev/',runScripts:'outside-only'});
const d=dom.window.document,h=d.getElementById('dashboardHomeContent');
assert(h,'homepage remains available');
const tiles=[...h.querySelectorAll('.main-menu-grid > button.main-menu-btn')];
assert.deepEqual(tiles.map(x=>x.textContent.trim()),['إضافة','سجل العمليات','التقارير','الحسابات']);
assert.equal(h.querySelectorAll('.ratib-commerce-shortcuts,.ratib-commerce-shortcut').length,0);
for(const word of ['المخزون','الوارد','الصادر'])assert(!h.textContent.includes(word),'retired '+word+' is not on the homepage');
assert.equal(d.querySelectorAll('#pageCommerce').length,1,'retired legacy mount kept for existing data');
assert.equal(d.getElementById('ratibCommerceDefaults').hidden,true);
assert(d.querySelector('[data-ledger-voucher-type="commerce"]'),'historical commercial ledger filter retained');
assert(d.querySelector('[data-ledger-voucher-type="commerce"]').closest('label').textContent.includes('سابقة'));
assert(!fav.includes('const commerceFavorites='),'retired features must not appear in catalog');
assert(fav.includes("!id.startsWith('commerce:')"),'previous favorites removed from displayed list');
for(const group of ['المخزون','الوارد','الصادر'])assert(!fav.includes('<option>'+group+'</option>'),'retired '+group+' not selectable');
assert(!home.includes('enhanceDashboard()'),'retired dashboard no longer initialized');
assert(!home.includes('if (!carousel || !commerce'));
assert(html.includes("if(saved.view.tab==='pageCommerce')return;"),'do not reopen commerce from previous session');
assert(sidebar.includes("const label='الإصدار '+v+' (تجريبية)'"),'trial label stays');
assert(html.includes("const CLOUD_FOLDER_NAME = 'Ratib Trial Backups'"),'trial backup destination must stay isolated');
assert(html.includes("const CLOUD_FILE_PREFIX = 'ratib-trial-cloud-'"),'trial backup prefix stays');
assert(html.includes("const CLOUD_LEGACY_FOLDER_NAME = 'Ratib Backups'"),'official folder accessible only via guarded manual choice');
assert(html.includes("const CLOUD_CFG_KEY = 'cloud_backup_cfg'"),'backups keep original storage key');
assert(html.includes("store.get('commerce_v1',null)"),'existing historical invoices still readable');
for(const [label,js] of [['favorites',fav],['homepage',home],['service-worker',sw]])assert.doesNotThrow(()=>new Function(js),label+' syntax');
dom.window.close();
console.log('PASS trial '+release+': simplified homepage and favorites, trial branding/backup isolation, historical records');
