'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const src=fs.readFileSync('ratib-interactive-tree-3.6.105.05.js','utf8');
const a=src.indexOf(' function makeStats(){'),b=src.indexOf(' function activity(',a);
assert(a>=0&&b>a);
const nodes=new Map();
for(let i=0;i<15;i++)nodes.set('internal'+i,{kind:'sub',sums:new Map()});
for(let i=0;i<8;i++)nodes.set('account'+i,{kind:'detail',sums:new Map()});
const statsBox={innerHTML:''},money=n=>String(n),window={RatibSimpleAccounts:{GROUPS:['cash','clients','suppliers','income','expenses','other'].map(id=>({id}))}};
const render=new Function('nodes','statsBox','money','window',src.slice(a,b)+';makeStats()');
render(nodes,statsBox,money,window);
const count=label=>Number(statsBox.innerHTML.match(new RegExp('<b>(\\d+)</b><small>'+label+'</small>'))?.[1]);
assert.equal(count('الحسابات الرئيسية'),5);
assert.equal(count('الحسابات الفرعية'),8);
assert.equal(count('إجمالي الحسابات'),13);
assert.equal(count('عملات بها حركات'),0);
nodes.set('account8',{kind:'detail',sums:new Map([['YER',{debit:10,credit:0}]])});
render(nodes,statsBox,money,window);
assert.equal(count('الحسابات الفرعية'),9);
assert.equal(count('إجمالي الحسابات'),14);
assert.equal(count('عملات بها حركات'),1);
console.log('PASS: visible simplified account statistics, 5 primary + 8 detail = 13 total; safe growth');
