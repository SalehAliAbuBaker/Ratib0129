'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {JSDOM}=require('jsdom');
const src=fs.readFileSync('ratib-document-signatures-3.6.148.js','utf8');
const notice='هذا السند آلي لا يحتاج لختم أو توقيع';
const dom=new JSDOM('<!doctype html><html><head></head><body><div id="pageSettings"><section class="settings-accordion-card"><div class="settings-accordion-header">الحسابات الافتراضية للسندات</div><div class="settings-accordion-body"></div></section></div><div class="pv-signatures"><div class="old-signatures">القديم</div></div></body></html>',{url:'https://ratib.test/'});
const db=new Map(),store={get:(k,d)=>db.has(k)?structuredClone(db.get(k)):d,set:(k,v)=>db.set(k,structuredClone(v))};
const ctx={document:dom.window.document,window:dom.window,store,localStorage:dom.window.localStorage,console};
vm.createContext(ctx);vm.runInContext(src,ctx);
const api=ctx.window.RatibSignatureSettings;
assert(api,'Signature module loaded');
const original=api.get('receipt'),names=Array.from(original.people.map(p=>p.label));
assert.equal(original.automatic,false);
assert.deepEqual(names,['المحاسب / المدير','أمين الصندوق','المستفيد']);
assert(api.html('receipt').includes('أمين الصندوق'));
assert.equal(api.put('receipt',{...original,automatic:true}),true);
const automatic=api.get('receipt');
assert.equal(automatic.automatic,true);
assert.deepEqual(Array.from(automatic.people.map(p=>p.label)),names);
assert(automatic.enabled);
assert(api.html('receipt').includes(notice));
assert(!api.html('receipt').includes('أمين الصندوق'));
assert.equal(api.height('receipt'),66);
const calls=[],canvas={save(){calls.push('save')},restore(){calls.push('restore')},fillText:(...args)=>calls.push(args)};
assert.equal(api.drawCanvas(canvas,'receipt',1190,1200),66);
assert(calls.some(x=>Array.isArray(x)&&x[0]===notice),'The PDF canvas uses the same notice');
api.fillVoucher('receipt');
const host=dom.window.document.querySelector('.pv-signatures .ratib-sig-print-host');
assert(host&&host.textContent.trim()===notice);
assert.equal(dom.window.document.querySelector('.old-signatures').style.display,'none');
const panel=dom.window.document.querySelector('#ratibSignatureSettings');
assert(panel&&panel.textContent.includes('خيارات المستند'));
const selected=panel.querySelector('#ratibSignatureType');
selected.value='receipt';selected.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
const toggle=panel.querySelector('#ratibSignatureAutomatic');
assert(toggle.checked);
assert(panel.querySelector('#ratibSignatureRows').hidden);
toggle.checked=false;toggle.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert(!panel.querySelector('#ratibSignatureRows').hidden);
panel.querySelector('#ratibSignatureSave').click();
assert.equal(api.get('receipt').automatic,false);
assert.deepEqual(Array.from(api.get('receipt').people.map(p=>p.label)),names);
api.fillVoucher('receipt');
assert(host.textContent.includes('أمين الصندوق'));
assert(!host.textContent.includes(notice));
assert.equal(api.height('receipt'),103);
assert.equal(api.put('payment',{...api.get('payment'),automatic:true}),true);
assert.equal(api.get('receipt').automatic,false);
assert.equal(api.get('payment').automatic,true);
assert(api.reset('payment'));
assert.equal(api.get('payment').automatic,false);
console.log('PASS document options: original signatures, optional auto notice, per-type persistence, print/preview and PDF, safe restoration');
